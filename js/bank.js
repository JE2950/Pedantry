// ════════════════════════════════════════════════════════════════
// PEDANTRY, THE GAME: the question bank
//
// Each department has a character (stored under 'robot'), a rule card and a list of items.
//
// Gap items are written as one string:
//   'Sentence with ___ in it | right answer | wrong answer | another wrong answer :: why'
// The first answer after the sentence is always the right one. The game shuffles them.
// Every gap item works in all three games: Fill the Gap, Red Pen (spot the error)
// and the Rejection Desk (approve or reject).
//
// Verdict items (the Hall of False Rules) are written as:
//   'Sentence :: ok :: why'     (the sentence is fine)
//   'Sentence :: no :: why'     (the sentence has a mistake)
// These only appear on the Rejection Desk.
// ════════════════════════════════════════════════════════════════

function gap(src, dept) {
  const [body, why] = src.split('::').map(s => s.trim());
  const parts = body.split('|').map(s => s.trim());
  return { kind: 'gap', dept, s: parts[0], a: parts[1], w: parts.slice(2), why };
}
function verdict(src, dept) {
  const [s, ok, why] = src.split('::').map(x => x.trim());
  return { kind: 'verdict', dept, s, ok: ok === 'ok', why };
}

